/*
 * SSD1306 128x64 I2C OLED driver (minimal, framebuffer-based).
 */

#include "oled.h"

#include <string.h>

static uint8_t fb[OLED_FB_SIZE];

static const I2CConfig i2c_cfg = {
  0x00303D5BU,  /* TIMINGR: ~400 kHz @ 85 MHz PCLK1 */
  0U,
  0U
};

static void cmd(const uint8_t *data, size_t n) {
  static uint8_t buf[32];
  size_t i;

  buf[0] = 0x00U;
  for (i = 0; i < n; i++) {
    buf[i + 1U] = data[i];
  }

  (void)i2cMasterTransmitTimeout(&I2CD1, OLED_I2C_ADDR, buf, n + 1U,
                                 NULL, 0U, TIME_MS2I(20));
}

static void flush_fb(void) {
  static uint8_t txbuf[1U + OLED_FB_SIZE];

  txbuf[0] = 0x40U;
  memcpy(&txbuf[1], fb, OLED_FB_SIZE);

  (void)i2cMasterTransmitTimeout(&I2CD1, OLED_I2C_ADDR, txbuf,
                                 sizeof(txbuf), NULL, 0U, TIME_MS2I(100));
}

void oledInit(void) {

  palSetLineMode(PAL_LINE(GPIOB, 8U), PAL_MODE_ALTERNATE(4U));
  palSetLineMode(PAL_LINE(GPIOB, 9U), PAL_MODE_ALTERNATE(4U));

  i2cStart(&I2CD1, &i2c_cfg);

  static const uint8_t init1[] = {
    0xAEU,        /* display off */
    0xD5U, 0x80U, /* clock divide */
    0xA8U, 0x3FU, /* multiplex 64 */
    0xD3U, 0x00U, /* display offset 0 */
    0x40U,        /* start line 0 */
    0x8DU, 0x14U, /* charge pump on */
    0x20U, 0x00U, /* horizontal addressing */
    0xA1U,        /* segment remap */
    0xC8U,        /* COM scan decrement */
    0xDAU, 0x12U, /* COM pins */
    0x81U, 0xCFU, /* contrast */
    0xD9U, 0xF1U, /* precharge */
    0xDBU, 0x40U, /* VCOM detect */
    0xA4U,        /* resume from RAM */
    0xA6U,        /* normal (not inverted) */
    0xAFU         /* display on */
  };

  cmd(init1, sizeof(init1));

  oledClear();
  oledFlush();
}

void oledClear(void) {

  memset(fb, 0, OLED_FB_SIZE);
}

void oledFlush(void) {
  static const uint8_t addr[] = {
    0x21U, 0x00U, 0x7FU,  /* column 0..127 */
    0x22U, 0x00U, 0x07U   /* page 0..7 */
  };

  cmd(addr, sizeof(addr));
  flush_fb();
}

void oledSetPixel(uint16_t x, uint16_t y, bool on) {

  if (x >= OLED_WIDTH || y >= OLED_HEIGHT) {
    return;
  }

  if (on) {
    fb[x + (y / 8U) * OLED_WIDTH] |= (uint8_t)(1U << (y % 8U));
  }
  else {
    fb[x + (y / 8U) * OLED_WIDTH] &= (uint8_t)~(1U << (y % 8U));
  }
}

void oledDrawBitmap(uint16_t x, uint16_t y, uint16_t w, uint16_t h,
                    const uint8_t *bitmap) {
  uint16_t i;
  uint16_t j;

  for (j = 0; j < h; j++) {
    for (i = 0; i < w; i++) {
      uint16_t byte = j * ((w + 7U) / 8U) + i / 8U;
      uint8_t bit = (uint8_t)(0x80U >> (i % 8U));

      oledSetPixel(x + i, y + j,
                   (bitmap[byte] & bit) != 0U);
    }
  }
}

