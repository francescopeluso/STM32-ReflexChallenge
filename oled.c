void oledDrawChar(uint16_t x, uint16_t y, char c, uint8_t scale) {
  const uint8_t *glyph;
  uint16_t i;
  uint16_t j;

  if (c < 0x20 || c > 0x7E) {
    c = ' ';
  }

  glyph = font5x7[(uint8_t)c - 0x20U];

  for (j = 0; j < 7U; j++) {
    for (i = 0; i < 5U; i++) {
      if ((glyph[i] & (uint8_t)(1U << j)) != 0U) {
        uint16_t sx;
        uint16_t sy;

        for (sy = 0; sy < scale; sy++) {
          for (sx = 0; sx < scale; sx++) {
            oledSetPixel(x + i * scale + sx, y + j * scale + sy, true);
          }
        }
      }
    }
  }
}

uint16_t oledStrWidth(const char *str, uint8_t scale) {
  uint16_t w = 0U;

  while (*str != '\0') {
    w += 6U * scale;
    str++;
  }

  if (w > 0U) {
    w -= scale;
  }

  return w;
}

void oledDrawString(uint16_t x, uint16_t y, const char *str, uint8_t scale) {

  while (*str != '\0') {
    oledDrawChar(x, y, *str, scale);
    x += 6U * scale;
    str++;
  }
}

void oledUtoa(uint32_t v, char *buf, uint8_t digits) {
  uint8_t i;

  for (i = digits; i > 0U; i--) {
    buf[i - 1U] = (char)('0' + (v % 10U));
    v /= 10U;
  }

  buf[digits] = '\0';
}

