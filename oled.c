void oledDrawDigit16x24(uint16_t x, uint16_t y, uint8_t d) {
  const uint8_t *glyph;
  uint16_t i;
  uint16_t j;

  if (d > 9U) {
    d = 0U;
  }

  glyph = digits16x24[d];

  for (j = 0; j < 24U; j++) {
    for (i = 0; i < 16U; i++) {
      uint16_t byte = j * 2U + i / 8U;
      uint8_t bit = (uint8_t)(0x80U >> (i % 8U));

      if ((glyph[byte] & bit) != 0U) {
        oledSetPixel(x + i, y + j, true);
      }
    }
  }
}

